import type { JobState } from './types'

const AREA_LABELS: Record<string, string> = {
  idea_originality: 'Idea originality',
  works_as_promised: 'Works as promised',
  ui_ux: 'UI / UX',
  docs_readme: 'Docs / README',
}

/** The whole report as Markdown, ready to paste into a README, Devpost or a PR. */
export function toMarkdown(job: JobState): string {
  const out: string[] = ['# LaunchPad AI report', '']
  if (job.input) {
    out.push(`**Idea:** ${job.input.idea}  `, `**Repo:** ${job.input.repo_url}  `, `**Demo:** ${job.input.demo_url}`, '')
  }

  const j = job.judge
  if (j) {
    out.push(`## Score: ${j.total_score}/100`, '', '| Area | Score |', '|---|---|')
    for (const [k, v] of Object.entries(j.scores)) out.push(`| ${AREA_LABELS[k] ?? k} | ${v}/10 |`)
    out.push('', `> ${j.judge_comment}`, '', '### Top 3 fixes', '')
    j.top_3_fixes.forEach((f, i) => out.push(`${i + 1}. ${f}`))
    out.push('')
  }

  const o = job.originality
  if (o) {
    out.push(`## Originality: ${o.originality_score ?? '–'}/10`, '', o.summary, '')
    for (const p of o.similar_projects) out.push(`- [${p.name}](${p.url})${p.similarity ? ` (${p.similarity})` : ''}: ${p.how_different}`)
    if (o.how_to_stand_out.length) {
      out.push('', '**How to stand out**', '')
      o.how_to_stand_out.forEach((t) => out.push(`- ${t}`))
    }
    out.push('')
  }

  const t = job.testing
  if (t) {
    out.push(`## Bugs found by live agents (${t.bugs.length})`, '')
    for (const b of t.bugs) {
      const agent = job.agents[b.agent]?.name ?? b.agent
      out.push(`- **${b.severity.toUpperCase()}** ${b.problem}${b.where ? ` (${b.where})` : ''}. _Found by ${agent}_`)
    }
    if (!t.bugs.length) out.push('No bugs found.')
    out.push('')
  }

  out.push('---', '_Generated by LaunchPad AI with TinyFish browser agents._')
  return out.join('\n')
}
